# Exercício: Faça um programa, utilizando while, que mostre na tela os números de 0 a 100.

print("\n-- Laço de repetição de impressão de números de 0 a 100 para usuário --\n")

num = 0

while num < 101:
    print(num, end=" ")
    num += 1

print("\n\nFim do programa. Obrigado por visitar!\n")